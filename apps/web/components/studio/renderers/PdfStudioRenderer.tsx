'use client';

import React, { useState } from 'react';
import {
  FileText,
  RotateCw,
  Trash2,
  MoveUp,
  MoveDown,
  Plus,
  Download,
  Split,
  Combine,
  Highlighter,
  Stamp,
  Check,
  FileCheck2,
} from 'lucide-react';
import { useEditorStore } from '@/stores/editor-store';
import jsPDF from 'jspdf';
import toast from 'react-hot-toast';

export default function PdfStudioRenderer() {
  const { project, addPage, deletePage } = useEditorStore();

  const [pdfPages, setPdfPages] = useState([
    { id: 'pdf-p1', title: 'Executive Summary', rotation: 0, annotations: ['Reviewed & Approved'] },
    { id: 'pdf-p2', title: 'Financial Balance Sheet', rotation: 0, annotations: ['Audit Verified'] },
    { id: 'pdf-p3', title: 'System Architecture Specification', rotation: 0, annotations: [] },
    { id: 'pdf-p4', title: 'Service Level Agreement (SLA)', rotation: 0, annotations: [] },
  ]);

  const [selectedPageIndex, setSelectedPageIndex] = useState(0);
  const [stampText, setStampText] = useState('APPROVED');

  const handleRotatePage = (index: number) => {
    setPdfPages((prev) =>
      prev.map((p, i) => (i === index ? { ...p, rotation: (p.rotation + 90) % 360 } : p))
    );
    toast.success(`Rotated page ${index + 1} by 90°`);
  };

  const handleMovePage = (index: number, direction: 'up' | 'down') => {
    const targetIndex = direction === 'up' ? index - 1 : index + 1;
    if (targetIndex < 0 || targetIndex >= pdfPages.length) return;

    setPdfPages((prev) => {
      const copy = [...prev];
      const temp = copy[index];
      copy[index] = copy[targetIndex];
      copy[targetIndex] = temp;
      return copy;
    });
    setSelectedPageIndex(targetIndex);
    toast.success(`Moved page to position ${targetIndex + 1}`);
  };

  const handleDeletePdfPage = (index: number) => {
    if (pdfPages.length <= 1) {
      toast.error('Cannot delete the only page');
      return;
    }
    setPdfPages((prev) => prev.filter((_, i) => i !== index));
    setSelectedPageIndex((prev) => Math.max(0, prev - 1));
    toast.success(`Deleted page ${index + 1}`);
  };

  const handleAddAnnotationStamp = (index: number) => {
    setPdfPages((prev) =>
      prev.map((p, i) =>
        i === index ? { ...p, annotations: [...p.annotations, stampText] } : p
      )
    );
    toast.success(`Added "${stampText}" stamp to page ${index + 1}`);
  };

  const handleAddNewBlankPage = () => {
    const newPage = {
      id: `pdf-p${pdfPages.length + 1}`,
      title: `Page ${pdfPages.length + 1}`,
      rotation: 0,
      annotations: [],
    };
    setPdfPages((prev) => [...prev, newPage]);
    setSelectedPageIndex(pdfPages.length);
    toast.success('Inserted new page');
  };

  const handleExportCompiledPdf = () => {
    try {
      const doc = new jsPDF({
        orientation: 'portrait',
        unit: 'mm',
        format: 'a4',
      });

      pdfPages.forEach((page, index) => {
        if (index > 0) doc.addPage();

        // Header
        doc.setFontSize(16);
        doc.setTextColor(30, 41, 59);
        doc.text(page.title, 20, 25);

        doc.setFontSize(10);
        doc.setTextColor(100, 116, 139);
        doc.text(`VisualFlow Studio Compiled Document — Page ${index + 1} of ${pdfPages.length}`, 20, 32);
        doc.line(20, 35, 190, 35);

        // Body content simulation
        doc.setFontSize(11);
        doc.setTextColor(51, 65, 85);
        doc.text(
          `This document was processed and compiled with VisualFlow PDF Studio.\nPage rotation: ${page.rotation} degrees.\nTimestamp: ${new Date().toISOString()}`,
          20,
          50
        );

        // Stamp Annotations
        page.annotations.forEach((ann, aIdx) => {
          doc.setTextColor(220, 38, 38);
          doc.setFontSize(14);
          doc.rect(130, 45 + aIdx * 15, 55, 10);
          doc.text(`[ ${ann} ]`, 135, 52 + aIdx * 15);
        });

        // Footer
        doc.setFontSize(9);
        doc.setTextColor(148, 163, 184);
        doc.text(`Generated by VisualFlow Studio | Document ID: ${project?.id || 'demo'}`, 20, 285);
      });

      doc.save(`${project?.title || 'Document'}-compiled.pdf`);
      toast.success('Exported optimized PDF document');
    } catch (e) {
      console.error(e);
      toast.error('Failed to export PDF');
    }
  };

  const currentPage = pdfPages[selectedPageIndex];

  return (
    <div className="w-full h-full flex flex-col bg-slate-900 select-none overflow-hidden">
      {/* Top PDF Operations Ribbon */}
      <div className="h-14 bg-slate-950 border-b border-slate-800 px-6 flex items-center justify-between">
        <div className="flex items-center space-x-2">
          <div className="flex items-center space-x-1.5 bg-slate-900 p-1 rounded-lg border border-slate-800">
            <button
              onClick={() => handleRotatePage(selectedPageIndex)}
              className="px-2.5 py-1.5 rounded hover:bg-slate-800 text-xs font-semibold text-slate-300 hover:text-white flex items-center space-x-1.5 transition-colors"
              title="Rotate 90° Clockwise"
            >
              <RotateCw className="w-3.5 h-3.5 text-blue-400" />
              <span>Rotate</span>
            </button>
            <button
              onClick={() => handleMovePage(selectedPageIndex, 'up')}
              disabled={selectedPageIndex === 0}
              className="p-1.5 rounded hover:bg-slate-800 disabled:opacity-30 text-slate-300 hover:text-white transition-colors"
              title="Move Page Up"
            >
              <MoveUp className="w-4 h-4" />
            </button>
            <button
              onClick={() => handleMovePage(selectedPageIndex, 'down')}
              disabled={selectedPageIndex === pdfPages.length - 1}
              className="p-1.5 rounded hover:bg-slate-800 disabled:opacity-30 text-slate-300 hover:text-white transition-colors"
              title="Move Page Down"
            >
              <MoveDown className="w-4 h-4" />
            </button>
            <button
              onClick={() => handleDeletePdfPage(selectedPageIndex)}
              className="p-1.5 rounded hover:bg-rose-950 text-rose-400 hover:text-rose-200 transition-colors"
              title="Delete Page"
            >
              <Trash2 className="w-4 h-4" />
            </button>
          </div>

          <div className="w-px h-5 bg-slate-800 mx-2" />

          {/* Stamp Selector */}
          <div className="flex items-center space-x-1.5">
            <input
              type="text"
              value={stampText}
              onChange={(e) => setStampText(e.target.value)}
              placeholder="Stamp text..."
              className="bg-slate-900 border border-slate-700 rounded px-2 py-1 text-xs text-white w-28 focus:outline-none focus:border-rose-500"
            />
            <button
              onClick={() => handleAddAnnotationStamp(selectedPageIndex)}
              className="px-2.5 py-1 bg-rose-950/80 border border-rose-700/60 hover:bg-rose-900 rounded text-rose-300 text-xs font-semibold flex items-center space-x-1 transition-colors"
            >
              <Stamp className="w-3.5 h-3.5" />
              <span>Add Stamp</span>
            </button>
          </div>
        </div>

        {/* Right actions */}
        <div className="flex items-center space-x-2">
          <button
            onClick={handleAddNewBlankPage}
            className="px-3 py-1.5 bg-slate-900 hover:bg-slate-800 border border-slate-700 rounded-lg text-xs font-semibold text-slate-200 flex items-center space-x-1.5 transition-colors"
          >
            <Plus className="w-3.5 h-3.5 text-blue-400" />
            <span>Add Page</span>
          </button>
          <button
            onClick={handleExportCompiledPdf}
            className="px-3.5 py-1.5 bg-rose-600 hover:bg-rose-500 text-white rounded-lg text-xs font-bold flex items-center space-x-1.5 shadow-md shadow-rose-600/30 transition-all"
          >
            <Download className="w-4 h-4" />
            <span>Export Merged PDF</span>
          </button>
        </div>
      </div>

      {/* Main Body: Thumbnails Drawer on Left, Active Page View on Center */}
      <div className="flex-1 flex overflow-hidden">
        {/* Left Page Thumbnails Strip */}
        <div className="w-64 border-r border-slate-800 bg-slate-950 p-4 overflow-y-auto space-y-3">
          <div className="text-[10px] font-bold uppercase tracking-wider text-slate-400 mb-2">
            Document Pages ({pdfPages.length})
          </div>

          {pdfPages.map((page, idx) => (
            <div
              key={page.id}
              onClick={() => setSelectedPageIndex(idx)}
              className={`p-3 rounded-xl border cursor-pointer transition-all flex flex-col space-y-2 ${
                selectedPageIndex === idx
                  ? 'border-rose-500 bg-slate-900 shadow-md ring-2 ring-rose-500/20'
                  : 'border-slate-800 bg-slate-950 hover:border-slate-700'
              }`}
            >
              <div className="flex items-center justify-between text-xs">
                <span className="font-bold text-slate-200">Page {idx + 1}</span>
                {page.rotation > 0 && (
                  <span className="text-[10px] text-amber-400 bg-amber-950/60 px-1.5 py-0.5 rounded">
                    {page.rotation}°
                  </span>
                )}
              </div>

              {/* Mini visual mockup of page */}
              <div
                style={{ transform: `rotate(${page.rotation}deg)` }}
                className="h-28 bg-white rounded border border-slate-300 p-2 text-[8px] text-slate-700 flex flex-col justify-between overflow-hidden shadow-inner transition-transform"
              >
                <div>
                  <div className="font-bold truncate text-[9px] text-slate-900">{page.title}</div>
                  <div className="h-1 bg-slate-200 rounded w-3/4 my-1" />
                  <div className="h-1 bg-slate-200 rounded w-1/2" />
                </div>

                {page.annotations.length > 0 && (
                  <div className="border border-rose-500 text-rose-600 font-bold px-1 py-0.5 rounded text-[7px] text-center uppercase">
                    {page.annotations[0]}
                  </div>
                )}
              </div>
            </div>
          ))}
        </div>

        {/* Center High-DPI Page Viewer */}
        <div className="flex-1 p-8 overflow-y-auto flex items-center justify-center bg-slate-900 canvas-grid-pattern">
          {currentPage && (
            <div
              style={{
                width: '560px',
                minHeight: '780px',
                transform: `rotate(${currentPage.rotation}deg)`,
                boxShadow: '0 25px 50px -12px rgba(0, 0, 0, 0.5)',
              }}
              className="bg-white text-slate-900 p-12 rounded-sm border border-slate-300 relative transition-transform duration-300 flex flex-col justify-between"
            >
              <div>
                <div className="border-b-2 border-slate-800 pb-3 mb-6 flex items-center justify-between">
                  <h2 className="text-xl font-extrabold text-slate-900">{currentPage.title}</h2>
                  <span className="text-xs text-slate-500 font-mono">Page {selectedPageIndex + 1}</span>
                </div>

                <div className="space-y-4 text-xs text-slate-700 leading-relaxed">
                  <p>
                    VisualFlow Studio unified document layout model. This page preserves original DPI dimensions, vector curves, embedded fonts, and page break geometry.
                  </p>
                  <p>
                    Use the top toolbar to rotate pages, reorder document flow, delete unwanted pages, or stamp authorization signatures prior to final PDF compilation.
                  </p>
                </div>

                {/* Rendered Annotations / Stamps */}
                <div className="mt-8 flex flex-wrap gap-3">
                  {currentPage.annotations.map((ann, i) => (
                    <div
                      key={i}
                      className="px-4 py-2 border-2 border-rose-600 rounded-lg text-rose-600 font-extrabold text-sm uppercase tracking-wider rotate-[-6deg] shadow-sm select-none"
                    >
                      {ann}
                    </div>
                  ))}
                </div>
              </div>

              <div className="border-t border-slate-200 pt-3 text-[10px] text-slate-400 font-mono flex items-center justify-between">
                <span>VisualFlow Studio Document Engine</span>
                <span>Page {selectedPageIndex + 1} of {pdfPages.length}</span>
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
